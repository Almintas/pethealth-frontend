#!/usr/bin/env python3
"""Regenerates src/features/pet-passport/pdf/fonts.generated.ts.

The health passport PDF embeds a small subset of DejaVu Sans (regular and
bold) so that Lithuanian letters render the same in every PDF viewer. The PDF
uses one-byte character codes: 32-126 are ASCII, 128 and up are the extra
characters listed in EXTRA_CHARS below. Anything else is simplified before it
is drawn (see sanitize in pdf/encoding.ts).

Usage (needs fontTools and the DejaVu fonts, e.g. Debian's fonts-dejavu-core):

    python3 scripts/generate-pdf-fonts.py \
        /usr/share/fonts/truetype/dejavu/DejaVuSans.ttf \
        /usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf

DejaVu fonts: Bitstream Vera license + public-domain DejaVu changes; the
license text sits next to the generated module (DEJAVU-LICENSE.txt).
"""

import base64
import io
import sys

from fontTools import subset
from fontTools.agl import UV2AGL
from fontTools.ttLib import TTFont

ASCII_CHARS = "".join(chr(code) for code in range(32, 127))

# Order matters: the position in this string is the PDF code minus 128.
EXTRA_CHARS = (
    # Lithuanian
    "ĄąČčĘęĖėĮįŠšŲųŪūŽž"
    # Latvian
    "ĀāĒēĢģĪīĶķĻļŅņ"
    # Polish
    "ĆćŁłŃńÓóŚśŹźŻż"
    # Other Latin letters that turn up in names
    "ÄäÖöÜüßÕõÉéÈèÀàÁáÍíÚúÑñÇçÅåØø"
    # Punctuation and symbols
    "„“”‘’‚–—•…€°±×·©®™«»§µ"
)

OUTPUT = "src/features/pet-passport/pdf/fonts.generated.ts"


def glyph_name(char: str) -> str:
    code_point = ord(char)
    return UV2AGL.get(code_point, f"uni{code_point:04X}")


def build_font(path: str, chars: str) -> dict:
    options = subset.Options()
    options.glyph_names = True
    options.notdef_outline = True
    options.name_IDs = ["*"]
    options.name_legacy = True
    options.name_languages = ["*"]
    options.layout_features = []
    options.hinting = False
    options.drop_tables += ["GSUB", "GPOS", "GDEF", "kern"]

    font = TTFont(path)
    subsetter = subset.Subsetter(options)
    subsetter.populate(text=chars)
    subsetter.subset(font)

    buffer = io.BytesIO()
    font.save(buffer)
    data = buffer.getvalue()

    font = TTFont(io.BytesIO(data))
    units = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]

    def scale(value: float) -> int:
        return round(value * 1000 / units)

    widths = []
    for char in chars:
        glyph = cmap.get(ord(char))
        if glyph is None:
            raise SystemExit(f"{path} has no glyph for {char!r}")
        widths.append(scale(hmtx[glyph][0]))

    head = font["head"]
    os2 = font["OS/2"]
    return {
        "base64": base64.b64encode(data).decode("ascii"),
        "widths": widths,
        "ascent": scale(font["hhea"].ascent),
        "descent": scale(font["hhea"].descent),
        "capHeight": scale(getattr(os2, "sCapHeight", 0) or font["hhea"].ascent),
        "bbox": [
            scale(head.xMin),
            scale(head.yMin),
            scale(head.xMax),
            scale(head.yMax),
        ],
        "bytes": len(data),
    }


def ts_font(name: str, font: dict) -> str:
    lines = [
        f"  {name}: {{",
        f"    ascent: {font['ascent']},",
        f"    descent: {font['descent']},",
        f"    capHeight: {font['capHeight']},",
        f"    bbox: [{', '.join(str(v) for v in font['bbox'])}],",
        f"    widths: [{', '.join(str(v) for v in font['widths'])}],",
        f"    base64:\n      '{font['base64']}',",
        "  },",
    ]
    return "\n".join(lines)


def main() -> None:
    if len(sys.argv) != 3:
        raise SystemExit(__doc__)
    chars = ASCII_CHARS + EXTRA_CHARS
    if len(EXTRA_CHARS) > 128:
        raise SystemExit("EXTRA_CHARS must fit in codes 128-255")
    if len(set(chars)) != len(chars):
        raise SystemExit("EXTRA_CHARS has duplicates")

    regular = build_font(sys.argv[1], chars)
    bold = build_font(sys.argv[2], chars)

    names = [glyph_name(char) for char in chars]
    extra_literal = EXTRA_CHARS.replace("\\", "\\\\").replace("'", "\\'")
    content = "\n".join(
        [
            "/* eslint-disable */",
            "// Generated by scripts/generate-pdf-fonts.py — do not edit by hand.",
            "// DejaVu Sans subset (Bitstream Vera license, see DEJAVU-LICENSE.txt).",
            "",
            "/** Characters for PDF codes 128 and up, in code order. */",
            f"export const EXTRA_CHARS = '{extra_literal}';",
            "",
            "/** PostScript glyph names for codes 32-126, then 128 and up. */",
            "export const GLYPH_NAMES: readonly string[] = [",
            "  " + ", ".join(f"'{name}'" for name in names) + ",",
            "];",
            "",
            "export type EmbeddedFontData = {",
            "  ascent: number;",
            "  descent: number;",
            "  capHeight: number;",
            "  bbox: readonly [number, number, number, number];",
            "  /** Advance widths in 1/1000 em, same order as GLYPH_NAMES. */",
            "  widths: readonly number[];",
            "  base64: string;",
            "};",
            "",
            "export const DEJAVU_SANS: { regular: EmbeddedFontData; bold: EmbeddedFontData } = {",
            ts_font("regular", regular),
            ts_font("bold", bold),
            "};",
            "",
        ]
    )
    with open(OUTPUT, "w", encoding="utf-8") as handle:
        handle.write(content)
    print(
        f"wrote {OUTPUT}: regular {regular['bytes']} B, bold {bold['bytes']} B, "
        f"{len(chars)} characters"
    )


if __name__ == "__main__":
    main()
